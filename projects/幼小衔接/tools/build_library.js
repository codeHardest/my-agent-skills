function noTone(py) {
  return py
    .replace(/[āáǎà]/g,'a').replace(/[ōóǒò]/g,'o')
    .replace(/[ēéěè]/g,'e').replace(/[īíǐì]/g,'i')
    .replace(/[ūúǔù]/g,'u').replace(/[ǖǘǚǜü]/g,'v');
}

const seen = new Set();
const lib = [];
for (const row of TABLE) {
  const [ch, py, wordsStr, similarStr, groupOverride] = row;
  if (seen.has(ch)) throw new Error('重复字: ' + ch);
  seen.add(ch);
  const words = wordsStr.split(',');
  if (words.length < 3) throw new Error(ch + ' 组词不足3个: ' + words.join(','));
  lib.push({
    char: ch,
    pinyin: py,
    words: words,
    stroke_count: 0,
    strokes: [],
    phonetic_group: groupOverride || noTone(py),
    similar: similarStr ? similarStr.split(',') : [],
    level: 1
  });
}

// 相似字引用只保留字库内存在的；缺失的给出警告（便于后续维护）
const allChars = new Set(lib.map(e => e.char));
let dropped = 0;
for (const e of lib) {
  e.similar = e.similar.filter(s => {
    if (allChars.has(s)) return true;
    dropped++;
    console.warn(`⚠ ${e.char} 的相似字「${s}」不在字库中，已忽略`);
    return false;
  });
}
if (dropped) console.warn(`共忽略 ${dropped} 条越界相似引用`);

const out = path.join(__dirname, '..', 'data', 'char_library.json');
fs.writeFileSync(out, JSON.stringify(lib, null, 2) + '\n');
console.log('✓ 已生成 ' + lib.length + ' 字 →', out);
